function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function titleSizeClass(title) {
  if (title.length > 20) return 'game-title--extra-long';
  if (title.length > 17) return 'game-title--long';
  if (title.length > 12) return 'game-title--medium';
  return 'game-title--default';
}

export function validateSocialSnapshot(snapshot) {
  if (snapshot?.ok === false) {
    throw new Error(`Public snapshot endpoint reported ${String(snapshot.error || 'an unknown error')}.`);
  }
  if (!validateSnapshotShape(snapshot)) {
    throw new Error('Snapshot is missing required public arrays or contains invalid venue coordinates.');
  }

  const seenGameIds = new Set();
  const seenSlugs = new Set();
  for (const game of snapshot.games) {
    const gameId = String(game?.game_id || '').trim();
    const opponent = String(game?.opponent_name || '').trim();
    const slug = gameRouteParam(game);
    if (!gameId || !opponent || !slug) {
      throw new Error('Every game must have a game_id, opponent_name, and route slug.');
    }
    if (seenGameIds.has(gameId)) throw new Error(`Duplicate game_id in snapshot: ${gameId}`);
    if (seenSlugs.has(slug)) throw new Error(`Duplicate game route slug in snapshot: ${slug}`);
    seenGameIds.add(gameId);
    seenSlugs.add(slug);
  }

  return snapshot;
}

export function socialCardModel(snapshot, game) {
  const slug = gameRouteParam(game);
  const title = `Cal ${gameTitle(game)}`;
  const locationCount = snapshot.venues.length;
  const watchPartyCount = snapshot.watchParties
    .filter((party) => party?.game_id === game.game_id)
    .length;
  const shareUrl = `${SITE_ORIGIN}/share/${slug}/`;
  const imageUrl = `${SITE_ORIGIN}/assets/social-cards/${slug}.png`;

  return {
    gameId: game.game_id,
    slug,
    title,
    locationCount,
    watchPartyCount,
    shareUrl,
    imageUrl,
    metadataTitle: `${title} · ${locationCount} locations mapped · ${watchPartyCount} Watch ${watchPartyCount === 1 ? 'Party' : 'Parties'}`
  };
}

