async function endpointFromIndex() {
  const html = await readFile(join(repositoryRoot, 'index.html'), 'utf8');
  const tag = html.match(/<meta\b[^>]*\bname=["']cgb-data-endpoint["'][^>]*>/i)?.[0];
  const endpoint = tag?.match(/\bcontent=["']([^"']+)["']/i)?.[1]?.trim();
  if (!endpoint) throw new Error('Could not find the cgb-data-endpoint meta tag in index.html.');
  const url = new URL(endpoint);
  if (url.protocol !== 'https:' || url.hostname !== 'script.google.com') {
    throw new Error(`Refusing unexpected snapshot endpoint: ${url.origin}`);
  }
  return endpoint;
}

async function fetchSnapshot(endpoint) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 20_000);
  try {
    const response = await fetch(endpoint, { signal: controller.signal, redirect: 'follow' });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    let snapshot;
    try {
      snapshot = await response.json();
    } catch (error) {
      throw new Error(`response was not valid JSON: ${error.message}`);
    }
    return validateSocialSnapshot(snapshot);
  } catch (error) {
    const detail = error?.name === 'AbortError' ? 'request timed out after 20 seconds' : error.message;
    throw new Error(`Unable to fetch the public Apps Script snapshot: ${detail}`);
  } finally {
    clearTimeout(timeout);
  }
}

function runBrowser(browser, args) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(browser, args, { stdio: ['ignore', 'ignore', 'pipe'] });
    let stderr = '';
    child.stderr.setEncoding('utf8');
    child.stderr.on('data', (chunk) => { stderr += chunk; });
    child.once('error', reject);
    child.once('close', (code) => {
      if (code === 0) resolvePromise();
      else reject(new Error(`Headless browser exited with code ${code}: ${stderr.slice(-2000)}`));
    });
  });
}

async function assertPngDimensions(path) {
  const png = await readFile(path);
  const signature = png.subarray(0, 8).toString('hex');
  if (signature !== '89504e470d0a1a0a' || png.length < 24) throw new Error(`Invalid PNG output: ${path}`);
  const width = png.readUInt32BE(16);
  const height = png.readUInt32BE(20);
  if (width !== CARD_WIDTH || height !== CARD_HEIGHT) {
    throw new Error(`Unexpected PNG dimensions for ${path}: ${width}x${height}`);
  }
}

async function renderPng(svg, outputPath, browser, temporaryDirectory) {
  const sourcePath = join(temporaryDirectory, `${outputPath.split(/[\\/]/).at(-1)}.svg`);
  await writeFile(sourcePath, svg, 'utf8');
  await mkdir(dirname(outputPath), { recursive: true });
  await runBrowser(browser, [
    '--headless=new',
    '--no-sandbox',
    '--disable-gpu',
    '--disable-dev-shm-usage',
    '--disable-lcd-text',
    '--disable-font-subpixel-positioning',
    '--hide-scrollbars',
    '--force-device-scale-factor=1',
    `--window-size=${CARD_WIDTH},${CARD_HEIGHT}`,
    `--screenshot=${resolve(outputPath)}`,
    pathToFileURL(sourcePath).href
  ]);
  await assertPngDimensions(outputPath);
}

async function readPreviousManifest() {
  try {
    return JSON.parse(await readFile(manifestPath, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return { games: [] };
    throw new Error(`Could not read the generated social-card manifest: ${error.message}`);
  }
}

async function removeObsoleteOutputs(previousManifest, activeSlugs) {
  for (const game of previousManifest.games || []) {
    const slug = String(game?.slug || '');
    if (!slug || activeSlugs.has(slug)) continue;
    await rm(join(cardRoot, `${slug}.png`), { force: true });
    const pagePath = join(shareRoot, slug, 'index.html');
    try {
      const page = await readFile(pagePath, 'utf8');
      if (page.includes(GENERATED_MARKER)) await rm(join(shareRoot, slug), { recursive: true, force: true });
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
}

async function canReuseCard(previousManifest, model, outputPath) {
  if (previousManifest.renderer_version !== RENDERER_VERSION) return false;
  const previous = (previousManifest.games || []).find((game) => game?.game_id === model.gameId);
  if (!previous ||
      previous.slug !== model.slug ||
      previous.title !== model.title ||
      previous.locations_mapped !== model.locationCount ||
      previous.watch_parties !== model.watchPartyCount) return false;
  try {
    await assertPngDimensions(outputPath);
    return true;
  } catch (_) {
    return false;
  }
}

function sortGames(games) {
  return [...games].sort((a, b) =>
    Number(a.season || 0) - Number(b.season || 0) ||
    Number(a.schedule_order || 0) - Number(b.schedule_order || 0) ||
    String(a.game_id).localeCompare(String(b.game_id))
  );
}

export async function generateSocialCards() {
  const endpoint = await endpointFromIndex();
  const snapshot = await fetchSnapshot(endpoint);
  const models = sortGames(snapshot.games).map((game) => socialCardModel(snapshot, game));
  if (!models.length) throw new Error('The public snapshot contains no games to generate.');

  const previousManifest = await readPreviousManifest();
  let browser = null;
  let temporaryDirectory = null;
  try {
    await mkdir(cardRoot, { recursive: true });
    await mkdir(shareRoot, { recursive: true });
    for (const model of models) {
      const cardPath = join(cardRoot, `${model.slug}.png`);
      if (!await canReuseCard(previousManifest, model, cardPath)) {
        browser ||= findBrowser();
        temporaryDirectory ||= await mkdtemp(join(tmpdir(), 'cgb-social-cards-'));
        await renderPng(buildCardSvg(model), cardPath, browser, temporaryDirectory);
      }
      const pagePath = join(shareRoot, model.slug, 'index.html');
      await mkdir(dirname(pagePath), { recursive: true });
      await writeFile(pagePath, buildSharePage(model), 'utf8');
      console.log(`Generated ${model.slug}: ${model.locationCount} locations, ${model.watchPartyCount} Watch Parties`);
    }

    const activeSlugs = new Set(models.map((model) => model.slug));
    await removeObsoleteOutputs(previousManifest, activeSlugs);
    const manifest = {
      version: 1,
      renderer_version: RENDERER_VERSION,
      games: models.map((model) => ({
        game_id: model.gameId,
        slug: model.slug,
        title: model.title,
        locations_mapped: model.locationCount,
        watch_parties: model.watchPartyCount,
        image: `assets/social-cards/${model.slug}.png`,
        page: `share/${model.slug}/index.html`
      }))
    };
    await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  } finally {
    if (temporaryDirectory) await rm(temporaryDirectory, { recursive: true, force: true });
  }

  console.log(`Generated ${models.length} game social card${models.length === 1 ? '' : 's'} from the public snapshot.`);
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';
if (import.meta.url === invokedPath) {
  generateSocialCards().catch((error) => {
    console.error(`Social-card generation failed: ${error.message}`);
    process.exitCode = 1;
  });
}
